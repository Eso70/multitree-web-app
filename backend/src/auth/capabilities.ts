type CatalogDefinition = (typeof ALL_PERMISSION_DEFINITIONS)[number];
type BusinessPermissionDefinition = Extract<
  CatalogDefinition,
  { readonly key: `business:${string}` }
>;

export const PERMISSION_CATALOG: readonly BusinessPermissionDefinition[] =
  ALL_PERMISSION_DEFINITIONS.filter(
    (item): item is BusinessPermissionDefinition =>
      item.key.startsWith('business:'),
  );

export type PermissionKey = (typeof PERMISSION_CATALOG)[number]['key'];

export const PERMISSION_BY_KEY = new Map<PermissionKey, PermissionDefinition>(
  PERMISSION_CATALOG.map((item) => [item.key, item]),
);

export function isPermissionKey(value: string): value is PermissionKey {
  return PERMISSION_BY_KEY.has(value as PermissionKey);
}

